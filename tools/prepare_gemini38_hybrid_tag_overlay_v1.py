"""One explicitly recovered fact tag overlays an immutable failed firstpass tag.

The frozen retrieval manifest/scientific protocol and native/H code objects stay
unchanged. An execution sidecar and new selected-source schema bind recovery.
No other original tag/cache is rewritten or regenerated by this module.
"""
from __future__ import annotations
import argparse
import copy
import hashlib
import importlib
import json
from pathlib import Path
import sys
from types import FunctionType
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools import prepare_gemini38_hybrid_effective40_v1 as base
from tools import mem0_regroup_firstpass_review_v2 as idx
from tools.run_sdk20_modules import save_new,now,digest
from jev_mem.providers import ModelAPI
from jev_mem.selection import tag_fact

admission=base.admission
SCHEMA=base.SCHEMA  # Existing scientific artifacts remain honestly on their original protocol.
SOURCE_SCHEMA='gemini38-effective40-tag-overlay-seven-arm-selected-inputs-v1'
OVERLAY_SCHEMA='gemini38-single-fact-tag-recovery-overlay-v1'
FAILED_CONVERSATION=2
FAILED_FACT_ID='60d7f398-b6e7-48ef-88b3-a478318ee11c'
REQUEST_HASH='9b4b45484cc4ebeca262b730ada1d3a5a000bb7a784a11d44cfb76735ae76df5'
SOURCE_NAME='selected_inputs_tag_overlay_v1.json'
CODE=tuple(dict.fromkeys((*base.CODE,'tools/prepare_gemini38_hybrid_tag_overlay_v1.py',
    'tools/recover_gemini38_fact_tag_v1.py')))
require=admission.require


def clone(function,scope,name=None):
    out=FunctionType(function.__code__,scope,name or function.__name__,function.__defaults__,function.__closure__)
    out.__kwdefaults__=dict(function.__kwdefaults__ or {});out.__module__=__name__;out.__qualname__=name or function.__name__
    return out


def _recovery_validate(namespace):
    module=importlib.import_module('tools.recover_gemini38_fact_tag_v1')
    return module.validate_recovery(namespace)


def _execution_codes():return {p:base._scope['sha'](ROOT/p)for p in CODE}
def sidecar_path(run):return Path(run).resolve()/'retrieval/tag_recovery_overlay_v1.json'
def source_path(run):return Path(run).resolve()/'retrieval'/SOURCE_NAME
def failed_path(run):return Path(run).resolve()/f'retrieval/conv_{FAILED_CONVERSATION}/tags/{FAILED_FACT_ID}.json'


def recovery_record(run,scientific,namespace):
    namespace=Path(namespace).resolve();run=Path(run).resolve()
    require(namespace!=run and not namespace.is_relative_to(run) and not run.is_relative_to(namespace),
        'Tag recovery must be a separate new namespace')
    manifest,terminal,review=_recovery_validate(namespace)
    require(manifest.get('schema')=='gemini38-fact-tag-exact-recovery-v1'
        and manifest.get('original_protocol_sha256')==scientific['protocol_sha256']
        and manifest.get('source_manifest')==idx.pointer(run/'retrieval/run_manifest.json'),
        'Recovery must bind this unchanged scientific retrieval manifest')
    require(manifest.get('policy',{}).get('retries')==0 and manifest['policy'].get('one_dispatch')is True
        and manifest['policy'].get('cache_roots')==[],'Only the reviewed one-dispatch/no-cache recovery policy is admitted')
    require(terminal.get('status')=='complete' and terminal.get('schema')==manifest['schema'],
        'Successful terminal exact-request recovery required')
    old_ref=idx.pointer(failed_path(run));old=idx.verify(failed_path(run))
    require(old.get('status')=='failed' and old.get('conversation')==FAILED_CONVERSATION and old.get('fact_id')==FAILED_FACT_ID
        and old_ref==manifest.get('failed_tag')==terminal.get('original_failed_tag'),
        'The one original failed tag must remain present and byte-bound')
    require(manifest.get('original_request_hash')==terminal.get('original_request_hash')==terminal.get('new_request_hash')==REQUEST_HASH,
        'Only the one pinned complete exact request may be recovered')
    original_intent=idx.bound(manifest['original_request_intent'])
    raw=idx.bound(terminal['new_raw'])
    signature=raw['request']
    require(signature==original_intent['signature']
        and hashlib.sha256(json.dumps(signature,sort_keys=True,ensure_ascii=False).encode()).hexdigest()==REQUEST_HASH
        and (signature.get('provider'),signature.get('model'),signature.get('operation'))==('jev','jev-1.13.0','systemone'),
        'Complete recovered request differs; same parsed text or scores is insufficient')
    record=terminal.get('fact_tag_record')
    require(isinstance(record,dict) and record.get('status')=='complete','Recovered scientific tag row missing')
    fields=('schema','protocol_sha256','conversation','fact_id','bank','fact_text_sha256','source_context_sha256','source_scope')
    require(all(record.get(k)==old.get(k)for k in fields)
        and record.get('protocol_sha256')==scientific['protocol_sha256']
        and record.get('result',{}).get('fact_id')==FAILED_FACT_ID,'Recovered fact/source identity changed')
    base._scope['_complete_fact_scores'](record['result'],FAILED_FACT_ID)
    require(record['result'].get('criteria_evaluations')==10,'Exactly10 original fact typing scores required')
    bank_item=next(x for x in scientific['banks']if(x['conversation'],x['arm'])==(FAILED_CONVERSATION,'session'))
    require(bank_item['bank']==record['bank'],'Recovered tag belongs to another current session bank')
    bank=idx.verify(admission.checked(bank_item['bank']))
    fact=next(f for f in bank['facts']if f['id']==FAILED_FACT_ID)
    session=fact.get('input_scope',{}).get('session_id');context=base.session_contexts(FAILED_CONVERSATION)[session]
    class Replay:
        score_many=ModelAPI.score_many  # Original response parser; no ModelAPI instance or credentials.
        def request(self,provider,model,body,*,operation,stage):
            require({'provider':provider,'model':model,'operation':operation,'body':body}==signature and stage=='jev_score',
                'Replayed current fact/context/ten criteria differ from complete recovered request')
            return raw['response']
    require(tag_fact({**fact,'source_context':context},Replay())==record['result'],
        'Recovered score/prompt metadata does not replay from its actual raw response')
    require(manifest.get('review'),'Firstpass source review binding missing')
    return manifest,terminal,review,record,old_ref


def prepare(run,recovery_namespace):
    run=Path(run).resolve();scientific,_=base.manifest(run,full=True)
    require(not sidecar_path(run).exists(),'Overlay sidecar exists; never overwrite or redo firstpass tags')
    m,t,review,record,old_ref=recovery_record(run,scientific,recovery_namespace)
    namespace=Path(recovery_namespace).resolve()
    value={'schema':OVERLAY_SCHEMA,'status':'complete_overlay_ready','created_utc':now(),
        'scientific_retrieval_manifest':idx.pointer(run/'retrieval/run_manifest.json'),
        'scientific_protocol_sha256':scientific['protocol_sha256'],'execution_code_sha256':_execution_codes(),
        'original_failed_tag':old_ref,'failed_conversation':FAILED_CONVERSATION,'failed_fact_id':FAILED_FACT_ID,
        'recovery_result':idx.pointer(namespace/'result.json'),'recovery_manifest':idx.pointer(namespace/'recovery_manifest.json'),
        'recovery_namespace':str(namespace),'firstpass_review':m['review'],
        'original_request_hash':REQUEST_HASH,'original_tag_stage_status':idx.pointer(run/'retrieval/tag_status.json'),
        'firstpass_tag_failure_preserved':True,'scientific_protocol_unchanged':True,
        'overlay_policy':'Only one original failed path resolves to one validated recovered tag row; no other tag is retagged.'}
    value['execution_protocol_sha256']=digest(value)
    save_new(sidecar_path(run),value)
    validate_overlay(run,scientific)
    return {'sidecar':idx.pointer(sidecar_path(run)),'model_calls':0,'firstpass_failed_tags_preserved':1}


def validate_overlay(run,scientific):
    run=Path(run).resolve();side=idx.verify(sidecar_path(run))
    require(side.get('schema')==OVERLAY_SCHEMA and side.get('status')=='complete_overlay_ready'
        and side.get('execution_protocol_sha256')==digest({k:v for k,v in side.items()if k not in ('execution_protocol_sha256','content_sha256')})
        and side.get('execution_code_sha256')==_execution_codes()
        and side.get('scientific_retrieval_manifest')==idx.pointer(run/'retrieval/run_manifest.json')
        and side.get('scientific_protocol_sha256')==scientific['protocol_sha256']
        and side.get('firstpass_tag_failure_preserved')is True and side.get('scientific_protocol_unchanged')is True,
        'Overlay execution/scientific protocol changed')
    require((side.get('failed_conversation'),side.get('failed_fact_id'),side.get('original_request_hash'))==
        (FAILED_CONVERSATION,FAILED_FACT_ID,REQUEST_HASH),'Overlay is outside exact one-failure allowance')
    m,t,review,record,old_ref=recovery_record(run,scientific,side['recovery_namespace'])
    namespace=Path(side['recovery_namespace']).resolve()
    require(side.get('original_failed_tag')==old_ref
        and side.get('recovery_manifest')==idx.pointer(namespace/'recovery_manifest.json')
        and side.get('recovery_result')==idx.pointer(namespace/'result.json')
        and side.get('firstpass_review')==m['review']
        and side.get('original_tag_stage_status')==idx.pointer(run/'retrieval/tag_status.json'),
        'Overlay original/recovery source pointers changed')
    return side,record


def manifest(run,conversation=None,full=False):
    scientific,pack=base.manifest(run,conversation,full)
    validate_overlay(run,scientific)
    return scientific,pack


_scope=dict(base._scope)
for _name,_function in base._scope.items():
    if isinstance(_function,FunctionType) and _function.__globals__ is base._scope:
        _scope[_name]=clone(_function,_scope,_name)
_scope.update(manifest=manifest,SOURCE_SCHEMA=SOURCE_SCHEMA)
for _name,_function in tuple(_scope.items()):
    if isinstance(_function,FunctionType) and _function.__module__==__name__:
        globals()[_name]=_function


def _load_tags(run,ci,bank,bank_ref,scientific):
    side,record=validate_overlay(run,scientific)
    exact=failed_path(run)
    def verify(path):
        if Path(path).resolve()==exact:
            require(ci==FAILED_CONVERSATION and bank_ref==record['bank'],'Overlay requested under another conversation/bank')
            require(idx.pointer(exact)==side['original_failed_tag'],'Original failed row SHA changed before mapping')
            return copy.deepcopy(record)
        return base._scope['verify'](path)
    core=clone(base._scope['_load_tags'],{**_scope,'verify':verify},'_load_tags_core')
    return core(run,ci,bank,bank_ref,scientific)


_scope['_load_tags']=_load_tags
_run_stage_core=_scope['run_stage']
_validate_source_core=_scope['validate_source']


def run_stage(run,stage,conversations=tuple(range(10)),workers=8,api_factory=None):
    require(stage=='retrieve','Overlay never repeats original tag/Writer stages')
    return _run_stage_core(run,stage,conversations,workers,api_factory)


def seal(run):
    run=Path(run).resolve();scientific,_=manifest(run,full=True);side,_=validate_overlay(run,scientific)
    exact=(run/'retrieval/selected_inputs.json').resolve();destination=source_path(run)
    require(not destination.exists(),'New overlay selected source already exists')
    def save(path,value):
        if Path(path).resolve()==exact:
            require(value['schema']==SOURCE_SCHEMA,'Overlay source schema differs')
            value={**value,'tag_recovery_overlay':idx.pointer(sidecar_path(run)),
                'tag_recovery_execution_protocol_sha256':side['execution_protocol_sha256'],
                'tag_firstpass_complete':False,'tag_firstpass_failed_tags':1}
            return save_new(destination,value)
        return save_new(path,value)
    def pointer(path):return base._scope['pointer'](destination if Path(path).resolve()==exact else path)
    def validate(path):return validate_source(destination if Path(path).resolve()==exact else path)
    core=clone(base._scope['seal'],{**_scope,'save_new':save,'pointer':pointer,'validate_source':validate},'_seal_core')
    return core(run)


def validate_source(path):
    source=base._scope['verify'](path);run=Path(source['parent_run']).resolve()
    require(Path(path).resolve()==source_path(run) and source.get('schema')==SOURCE_SCHEMA,
        'Explicit new overlay selected source required; no legacy fallback')
    scientific,_=manifest(run,full=True);side,_=validate_overlay(run,scientific)
    require(source.get('tag_recovery_overlay')==idx.pointer(sidecar_path(run))
        and source.get('tag_recovery_execution_protocol_sha256')==side['execution_protocol_sha256']
        and source.get('tag_firstpass_complete')is False and source.get('tag_firstpass_failed_tags')==1,
        'Selected source must disclose original failed firstpass and validated recovery')
    return _validate_source_core(path)


_scope.update(_load_tags=_load_tags,run_stage=run_stage,seal=seal,validate_source=validate_source,prepare=prepare)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('stage',choices=('prepare','check','retrieve','seal','validate-source'))
    p.add_argument('--run-dir',required=True,type=Path);p.add_argument('--recovery-namespace',type=Path);p.add_argument('--source',type=Path)
    p.add_argument('--conversations',nargs='+',type=int,default=list(range(10)));p.add_argument('--workers',type=int,default=8);a=p.parse_args()
    if a.stage=='prepare':
        require(a.recovery_namespace is not None,'Explicit completed recovery namespace required');result=prepare(a.run_dir,a.recovery_namespace)
    elif a.stage=='check':result={'valid':bool(manifest(a.run_dir,full=True)),'model_calls':0}
    elif a.stage=='seal':result=seal(a.run_dir)
    elif a.stage=='validate-source':result={'valid':bool(validate_source(a.source or source_path(a.run_dir))),'model_calls':0}
    else:result=run_stage(a.run_dir,'retrieve',tuple(a.conversations),a.workers)
    print(json.dumps(result,ensure_ascii=False))

if __name__=='__main__':main()
